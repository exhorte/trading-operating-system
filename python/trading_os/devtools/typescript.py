"""The cockpit's TypeScript types, generated from the core's own schemas — so the browser never keeps a hand-written copy of a contract
(ADR 0016: one model, in Python, is the truth).

Two sources feed one file:

* the OpenAPI document (``create_app(...).openapi()``): every schema becomes a type, every operation becomes an entry of a typed table
  (method, path, path/query parameters, request body, success response) that ``lib/api/client.ts`` is built on;
* the events (``EVENT_REGISTRY``) and the WebSocket snapshot: the payload of each frame, by wire type.

The output is deterministic (sorted) so a change in the core shows as a diff, and a test fails when the committed file is stale.
Pydantic marks a field that has a default as *required* in what the server **sends** (it is always there) and optional in what a
client **sends**: where a model is used both ways FastAPI emits ``X-Input`` and ``X-Output``; here they become ``XInput`` and
``XOutput`` and ``X`` is the Output (what you read).
"""

from __future__ import annotations

import json
import re
from collections.abc import Mapping
from typing import Any

_IDENTIFIER = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")
HEADER = (
    "/* eslint-disable */\n"
    "// GENERATED by `python -m trading_os gen-types` from the core's OpenAPI document and its event models.\n"
    "// Do not edit: change the model in Python and generate again (a test fails when this file is stale).\n"
)
ENVELOPE_FIELDS = {"id", "occurredAt", "accountId", "correlationId"}


PRESENTATION_KEYS = frozenset({"title", "description", "default", "examples"})


def structure(schema: Any) -> Any:
    """A schema without what does not change the type it describes (titles, descriptions, default values)."""
    if isinstance(schema, dict):
        return {k: structure(v) for k, v in schema.items() if k not in PRESENTATION_KEYS}
    if isinstance(schema, list):
        return [structure(v) for v in schema]
    return schema


def read_side(node: Any, names: set[str]) -> Any:
    """Point every reference at the variant a client READS: ``X`` becomes ``X-Output`` where the OpenAPI document split ``X`` into
    ``X-Input`` and ``X-Output`` (a standalone model schema, like an event's, knows only ``X``)."""
    if isinstance(node, dict):
        out: dict[str, Any] = {}
        for key, value in node.items():
            if key == "$ref" and isinstance(value, str):
                name = value.rsplit("/", 1)[-1]
                if name not in names and f"{name}-Output" in names:
                    value = value.rsplit("/", 1)[0] + f"/{name}-Output"
                out[key] = value
            else:
                out[key] = read_side(value, names)
        return out
    if isinstance(node, list):
        return [read_side(v, names) for v in node]
    return node


def type_name(schema_name: str) -> str:
    """``RiskProfile-Output`` → ``RiskProfileOutput``."""
    return re.sub(r"[^A-Za-z0-9_]", "", schema_name.replace("-", "_").replace("_", "")) or "Unknown"


def quote_key(key: str) -> str:
    return key if _IDENTIFIER.match(key) else json.dumps(key)


class Schemas:
    """Turns JSON-schema fragments into TypeScript type expressions. ``named`` maps a schema name to the name its type is declared by."""

    def __init__(self, components: Mapping[str, Any], aliases: Mapping[str, str] | None = None) -> None:
        self.components = components
        self.aliases = dict(aliases or {})

    def reference(self, ref: str) -> str:
        name = ref.rsplit("/", 1)[-1]
        if name not in self.components:
            raise KeyError(f"unresolved schema reference {ref!r}")
        return self.aliases.get(name, type_name(name))

    def of(self, schema: Mapping[str, Any]) -> str:
        if "$ref" in schema:
            return self.reference(schema["$ref"])
        if "const" in schema:
            return json.dumps(schema["const"])
        if "enum" in schema:
            return " | ".join(json.dumps(v) for v in schema["enum"]) or "never"
        for key, joiner in (("anyOf", " | "), ("oneOf", " | "), ("allOf", " & ")):
            if key in schema:
                parts = [self.of(part) for part in schema[key]]
                unique = list(dict.fromkeys(parts))
                return joiner.join(f"({p})" if " " in p and joiner == " & " and "|" in p else p for p in unique)
        kind = schema.get("type")
        if isinstance(kind, list):
            return " | ".join(dict.fromkeys(self.of({**schema, "type": k}) for k in kind))
        if kind == "string":
            return "string"
        if kind in ("integer", "number"):
            return "number"
        if kind == "boolean":
            return "boolean"
        if kind == "null":
            return "null"
        if kind == "array":
            if "prefixItems" in schema:
                return "[" + ", ".join(self.of(item) for item in schema["prefixItems"]) + "]"
            inner = self.of(schema.get("items", {}))
            return f"({inner})[]" if " " in inner else f"{inner}[]"
        if kind == "object" or "properties" in schema or "additionalProperties" in schema:
            return self.object_type(schema)
        return "unknown"

    def object_type(self, schema: Mapping[str, Any]) -> str:
        properties: Mapping[str, Any] = schema.get("properties", {})
        if not properties:
            extra = schema.get("additionalProperties", True)
            value = (
                "unknown" if extra is True or extra == {} else self.of(extra) if isinstance(extra, dict) else "never"
            )
            return f"Record<string, {value}>"
        required = set(schema.get("required", []))
        members = [
            f"{quote_key(key)}{'' if key in required else '?'}: {self.of(prop)};" for key, prop in properties.items()
        ]
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            members.append(f"[key: string]: {self.of(extra)};")
        return "{ " + " ".join(members) + " }"

    def declaration(self, name: str, schema: Mapping[str, Any]) -> str:
        target = self.aliases.get(name, type_name(name))
        description = schema.get("description")
        doc = f"/** {' '.join(str(description).split())} */\n" if description else ""
        if schema.get("type") == "object" or "properties" in schema:
            properties: Mapping[str, Any] = schema.get("properties", {})
            required = set(schema.get("required", []))
            if not properties:
                return f"{doc}export type {target} = {self.object_type(schema)};"
            lines = [f"{doc}export interface {target} {{"]
            for key, prop in properties.items():
                note = prop.get("description") if isinstance(prop, dict) else None
                if note:
                    lines.append(f"  /** {' '.join(str(note).split())} */")
                lines.append(f"  {quote_key(key)}{'' if key in required else '?'}: {self.of(prop)};")
            extra = schema.get("additionalProperties")
            if isinstance(extra, dict) and extra:
                lines.append(f"  [key: string]: {self.of(extra)};")
            lines.append("}")
            return "\n".join(lines)
        return f"{doc}export type {target} = {self.of(schema)};"


def friendly_aliases(components: Mapping[str, Any]) -> dict[str, str]:
    """``X-Output`` / ``X-Input`` become ``XOutput`` / ``XInput``; the plain ``X`` — what you read — is added as an alias by the caller."""
    return {name: type_name(name) for name in components}


def operations(document: Mapping[str, Any], schemas: Schemas) -> tuple[list[str], dict[str, tuple[str, str]]]:
    """The typed operation table, and ``operationId → (method, path)``."""
    entries: list[str] = []
    index: dict[str, tuple[str, str]] = {}
    for path, item in sorted(document["paths"].items()):
        for method, operation in sorted(item.items()):
            if method not in {"get", "post", "put", "patch", "delete"}:
                continue
            identifier = operation["operationId"]
            index[identifier] = (method.upper(), path)
            path_params: list[str] = []
            query_params: list[str] = []
            for parameter in operation.get("parameters", []):
                member = f"{quote_key(parameter['name'])}{'' if parameter.get('required') else '?'}: {schemas.of(parameter['schema'])};"
                (path_params if parameter["in"] == "path" else query_params).append(member)
            body = "undefined"
            request = operation.get("requestBody")
            if request is not None:
                content = request["content"]["application/json"]["schema"]
                body = schemas.of(content)
                if not request.get("required", False):
                    body += " | undefined"
            response = "void"
            for status, spec in sorted(operation["responses"].items()):
                if status.startswith("2"):
                    media = spec.get("content", {}).get("application/json")
                    response = schemas.of(media["schema"]) if media else "void"
                    break
            entries.append(
                f"  {identifier}: {{\n"
                f"    method: {json.dumps(method.upper())};\n"
                f"    path: {json.dumps(path)};\n"
                f"    pathParams: {record(path_params)};\n"
                f"    query: {record(query_params)};\n"
                f"    body: {body};\n"
                f"    response: {response};\n"
                f"  }};"
            )
    return entries, index


def record(members: list[str]) -> str:
    """An object type of these members; with none, a record that cannot hold anything (``{}`` would accept any value)."""
    return "{ " + " ".join(members) + " }" if members else "Record<string, never>"


def generate(
    document: Mapping[str, Any],
    event_schemas: Mapping[str, Mapping[str, Any]] | None = None,
    constants: Mapping[str, str | int] | None = None,
) -> str:
    """The whole ``generated.ts``. ``event_schemas`` maps a wire type (``risk.state_updated``) to the JSON schema of its event model
    (serialization mode, definitions under ``#/components/schemas`` like the OpenAPI document's). ``constants`` are the few
    values the core *compares by* or *refuses beyond* and the cockpit must recognise (the reason a kill switch is recorded under,
    how far back a strategy read may reach): emitted as constants so that no page keeps a copy that can drift."""
    components: dict[str, Any] = dict(document["components"]["schemas"])
    names = set(components)
    events = {wire: read_side(schema, names) for wire, schema in (event_schemas or {}).items()}
    for schema in events.values():
        for name, definition in schema.get("$defs", {}).items():
            target = name if name in components or f"{name}-Output" not in components else f"{name}-Output"
            existing = components.get(target)
            if existing is not None and structure(existing) != structure(definition):
                raise ValueError(f"two different schemas named {target!r} (OpenAPI and events)")
            components[target] = existing if existing is not None else definition
    schemas = Schemas(components, friendly_aliases(components))

    lines = [HEADER]
    lines.append(
        "// ----------------------------------------------------------------------------------------------- schemas"
    )
    for name in sorted(components, key=type_name):
        lines.append(schemas.declaration(name, components[name]))
    # « X » is what you read: the Output when a model exists in both directions
    declared = {type_name(n) for n in components}
    for name in sorted(components):
        if name.endswith("-Output") and type_name(name.removesuffix("-Output")) not in declared:
            lines.append(f"export type {type_name(name.removesuffix('-Output'))} = {type_name(name)};")

    table, index = operations(document, schemas)
    lines.append(
        "\n// ------------------------------------------------------------------------------------------- operations"
    )
    lines.append("export interface Operations {\n" + "\n".join(table) + "\n}\n")
    lines.append("export type OperationId = keyof Operations;")
    lines.append(
        'export const OPERATIONS: { [K in OperationId]: { method: Operations[K]["method"]; path: Operations[K]["path"] } } = {'
    )
    lines += [f"  {i}: {{ method: {json.dumps(m)}, path: {json.dumps(p)} }}," for i, (m, p) in sorted(index.items())]
    lines.append("};")

    lines.append(
        "\n// ----------------------------------------------------------------------------------------------- events"
    )
    envelope = "{ id: string; occurredAt: string; accountId: string | null; correlationId: string | null; }"
    lines.append(f"export type EventEnvelope = {envelope};")
    payloads: list[str] = []
    for wire_type, schema in sorted(events.items()):
        body = {k: v for k, v in schema.items() if k != "$defs"}
        properties = {k: v for k, v in body.get("properties", {}).items() if k not in ENVELOPE_FIELDS}
        payload = {
            **body,
            "properties": properties,
            "required": [r for r in body.get("required", []) if r in properties],
        }
        payloads.append(
            f"  {json.dumps(wire_type)}: {schemas.object_type(payload) if properties else 'Record<string, never>'};"
        )
    lines.append("export interface EventPayloads {\n" + "\n".join(payloads) + "\n}")
    lines.append("export type EventType = keyof EventPayloads;")
    lines.append(
        "export type CockpitEvent = { [K in EventType]: { type: K; payload: EventPayloads[K] } & EventEnvelope }[EventType];"
    )
    if constants:
        lines.append(
            "\n// --------------------------------------------------------------------------------------------- constants"
        )
        lines += [
            f"export const {name} = {json.dumps(value, ensure_ascii=False)} as const;"
            for name, value in sorted(constants.items())
        ]
    return "\n".join(lines) + "\n"
